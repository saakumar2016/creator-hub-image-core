// Cloudflare Pages response headers for the hosted remote (dist/_headers), generated at build
// time so the allowed shell origin comes from the environment, never from the repository.
//
// The shell imports remoteEntry.js and every chunk it loads with cross-origin module requests
// (mode "cors", no credentials, no preflight), so each of these files needs an
// Access-Control-Allow-Origin header that names the shell's origin. Pages sends
// "Access-Control-Allow-Origin: *" by default; a value in _headers replaces it.

/** The shell origin this deployment allows: https, origin only, never a local address. */
export function checkAllowedOrigin(value: string | undefined): { origin: string } | { problem: string } {
  if (!value || !value.trim()) return { problem: 'REMOTE_ALLOWED_ORIGIN is not set (the shell origin, e.g. https://<shell-project>.pages.dev)' }
  let url: URL
  try {
    url = new URL(value.trim())
  } catch {
    return { problem: `REMOTE_ALLOWED_ORIGIN is not a URL: ${value}` }
  }
  if (url.protocol !== 'https:') return { problem: `REMOTE_ALLOWED_ORIGIN must use https: ${value}` }
  if (url.username || url.password) return { problem: 'REMOTE_ALLOWED_ORIGIN must not contain credentials' }
  if (url.pathname !== '/' || url.search || url.hash) return { problem: `REMOTE_ALLOWED_ORIGIN must be an origin only (no path, query or hash): ${value}` }
  if (['localhost', '127.0.0.1', '[::1]'].includes(url.hostname) || url.hostname.endsWith('.localhost')) {
    return { problem: `REMOTE_ALLOWED_ORIGIN must not be a local address: ${value}` }
  }
  return { origin: url.origin }
}

/**
 * _headers for the remote: the entry is revalidated on every load (its name never changes),
 * hashed chunks are cached for a year. Only these two rules set Access-Control-Allow-Origin,
 * so no response ever carries two values.
 */
export function renderHeaders(origin: string): string {
  const common = [`  Access-Control-Allow-Origin: ${origin}`, '  Vary: Origin', '  X-Content-Type-Options: nosniff']
  return [
    '# Generated by scripts/pages-postbuild.ts from REMOTE_ALLOWED_ORIGIN. Do not edit by hand.',
    '/remoteEntry.js',
    ...common,
    '  Cache-Control: no-cache',
    '/assets/*',
    ...common,
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
  ].join('\n')
}
